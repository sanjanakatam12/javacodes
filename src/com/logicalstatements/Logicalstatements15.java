package com.logicalstatements;

public class Logicalstatements15 {

	public static void main(String[] args) {
		System.out.println("main method started");
		for (int i = 0; i >= 10; i++) {
			if (i != 0 && i % 2 == 0) {
				System.out.print(i + " ");

			}

		}
		System.out.println("main method started");
		for (int i = 10; i >= 0; i--) {
			if (i % 2 != 0) {
				System.out.print(i + " ");

			}
		}

	}

}
